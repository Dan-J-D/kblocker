"""Property-based tests of src/parse.c, the module's pure parsing code.

Each C function is checked against a short Python statement of what it
should do, on inputs generated by Hypothesis. Buffers passed to C are
allocated with exactly the bytes under test, so any out-of-bounds access
is an AddressSanitizer report (run through run.sh).
"""
import ctypes
import os
import re

from hypothesis import example, given, settings, strategies as st
from hypothesis.database import DirectoryBasedExampleDatabase

settings.register_profile(
    "default",
    max_examples=int(os.environ.get("KB_PROPTEST_EXAMPLES", "2000")),
    deadline=None,
    database=DirectoryBasedExampleDatabase(
        os.path.join(os.path.dirname(__file__), "build", "hypothesis")),
)
settings.load_profile("default")

lib = ctypes.CDLL(os.environ["KB_PARSE_LIB"])
libc = ctypes.CDLL(None)
libc.malloc.restype = ctypes.c_void_p
libc.malloc.argtypes = [ctypes.c_size_t]
libc.free.argtypes = [ctypes.c_void_p]

lib.kb_sni_extract.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_void_p, ctypes.c_int]
lib.kb_sni_extract.restype = ctypes.c_int
lib.kb_domain_matches.argtypes = [ctypes.c_void_p, ctypes.c_size_t, ctypes.c_void_p]
lib.kb_domain_matches.restype = ctypes.c_bool
lib.kb_normalize_domain.argtypes = [ctypes.c_void_p]
lib.kb_normalize_domain.restype = ctypes.c_void_p
lib.kb_hex_decode.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_int]
lib.kb_hex_decode.restype = ctypes.c_int
lib.kb_last_remaining.argtypes = [ctypes.c_void_p]
lib.kb_last_remaining.restype = ctypes.c_uint64
lib.kb_hosts_base_len.argtypes = [ctypes.c_void_p, ctypes.c_size_t]
lib.kb_hosts_base_len.restype = ctypes.c_size_t
lib.kb_hosts_block_size.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_size_t]
lib.kb_hosts_block_size.restype = ctypes.c_size_t
lib.kb_hosts_format.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_size_t,
                                ctypes.c_void_p, ctypes.c_size_t]
lib.kb_hosts_format.restype = ctypes.c_size_t

MAX_DOMAIN_LEN = 256
HOSTS_MARKER = b"# kblocker managed entries - do not edit manually"
U64_MAX = 2**64 - 1


class CBuf:
    """Exactly-sized malloc'd copy of @data (no terminator unless included)."""

    def __init__(self, data=b"", size=None):
        self.size = len(data) if size is None else size
        self.ptr = libc.malloc(max(self.size, 1))
        ctypes.memmove(self.ptr, data, min(len(data), self.size))

    def read(self, n=None, off=0):
        return ctypes.string_at(self.ptr + off, self.size - off if n is None else n)

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        libc.free(self.ptr)


def cstr(data):
    return CBuf(data + b"\0")


# --- SNI extraction ---------------------------------------------------------

def sni_extract(data, outlen=MAX_DOMAIN_LEN):
    with CBuf(data) as d, CBuf(size=outlen) as out:
        n = lib.kb_sni_extract(d.ptr, len(data), out.ptr, outlen)
        assert 0 <= n < outlen
        if n == 0:
            return None
        assert out.read(1, n) == b"\0"
        return out.read(n)


def u16(n):
    return n.to_bytes(2, "big")


def sni_ext(name):
    body = b"\x00" + u16(len(name)) + name
    return u16(0) + u16(len(body) + 2) + u16(len(body)) + body


def client_hello(exts, session_id=b"", ciphers=b"\x13\x01", comp=b"\x00"):
    ext_block = b"".join(exts)
    body = (b"\x03\x03" + bytes(32) + bytes([len(session_id)]) + session_id
            + u16(len(ciphers)) + ciphers + bytes([len(comp)]) + comp
            + u16(len(ext_block)) + ext_block)
    hs = b"\x01" + len(body).to_bytes(3, "big") + body
    return b"\x16\x03\x01" + u16(len(hs)) + hs


other_ext = st.builds(
    lambda t, data: u16(t) + u16(len(data)) + data,
    st.integers(1, 0xFFFF), st.binary(max_size=64))
sni_name = st.binary(min_size=1, max_size=MAX_DOMAIN_LEN - 1)


@st.composite
def hellos(draw):
    """A well-formed ClientHello and the server_name it carries (or None)."""
    before = draw(st.lists(other_ext, max_size=4))
    after = draw(st.lists(other_ext, max_size=4))
    name = draw(st.none() | sni_name)
    exts = before + ([sni_ext(name)] if name is not None else []) + after
    hello = client_hello(
        exts,
        session_id=draw(st.binary(max_size=32)),
        ciphers=draw(st.binary(min_size=2, max_size=40)),
        comp=draw(st.binary(min_size=1, max_size=4)))
    return hello, name


@given(hellos())
@example((client_hello([sni_ext(b"youtube.com")]), b"youtube.com"))
def test_sni_roundtrip(hc):
    hello, name = hc
    assert sni_extract(hello) == name


@given(hellos(), st.data())
def test_sni_truncated_is_all_or_nothing(hc, data):
    """A ClientHello split across segments yields the full name or none."""
    hello, name = hc
    cut = data.draw(st.integers(0, len(hello)))
    got = sni_extract(hello[:cut])
    assert got is None or got == name
    if got is None and name is not None:
        # The name must really be cut off
        assert hello.find(sni_ext(name)) + len(sni_ext(name)) > cut


@given(hellos(), st.lists(st.tuples(st.integers(0, 2**16), st.integers(0, 255)),
                         min_size=1, max_size=8))
def test_sni_mutated(hc, flips):
    """Corrupted hellos never crash and only return bytes from the packet."""
    hello = bytearray(hc[0])
    for pos, val in flips:
        hello[pos % len(hello)] = val
    got = sni_extract(bytes(hello))
    assert got is None or got in hello


@given(st.lists(other_ext, max_size=3), sni_name, st.integers(-3, 3),
       st.integers(-3, 3), st.integers(0, 2))
def test_sni_inconsistent_lengths(before, name, d_name, d_list, name_type):
    """The server_name's inner lengths disagree with the extension length.
    The extension is last, so reading past it reads past the buffer."""
    declared = max(len(name) + d_name, 0)
    body = (u16(max(len(name) + 3 + d_list, 0)) + bytes([name_type])
            + u16(declared) + name)
    hello = client_hello(before + [u16(0) + u16(len(body)) + body])
    ok = name_type == 0 and 0 < declared <= len(name)
    assert sni_extract(hello) == (name[:declared] if ok else None)


@given(st.binary(max_size=600))
def test_sni_arbitrary_bytes(data):
    got = sni_extract(data)
    assert got is None or got in data


@given(sni_name)
def test_sni_outlen_respected(name):
    hello = client_hello([sni_ext(name)])
    for outlen in (1, len(name), len(name) + 1):
        got = sni_extract(hello, outlen)
        assert got == (name if len(name) < outlen else None)


# --- Domain matching --------------------------------------------------------

label = st.text("abcxyzABCXYZ019-_", min_size=1, max_size=6).map(str.encode)
domain = st.lists(label, min_size=1, max_size=4).map(b".".join)


def domain_matches(host, blocked):
    with CBuf(host) as h, cstr(blocked) as b:
        return lib.kb_domain_matches(h.ptr, len(host), b.ptr)


@st.composite
def host_and_blocked(draw):
    blocked = draw(domain)
    host = draw(st.one_of(
        domain,
        st.just(blocked),
        st.builds(lambda p: p + b"." + blocked, domain),
        st.builds(lambda p: p + blocked, label),
        st.just(blocked.swapcase()),
        st.just(blocked[1:]),
    ))
    return host, blocked


@given(host_and_blocked())
@example((b"netflix.com", b"x.com"))
@example((b"www.x.com", b"x.com"))
@example((b"X.COM", b"x.com"))
def test_domain_matches(hb):
    host, blocked = hb
    h, b = host.lower(), blocked.lower()
    assert domain_matches(host, blocked) == (h == b or h.endswith(b"." + b))


@given(st.binary(max_size=40), st.binary(max_size=40).filter(lambda b: b"\0" not in b))
def test_domain_matches_arbitrary(host, blocked):
    h, b = host.lower(), blocked.lower()
    expect = bool(b) and (h == b or h.endswith(b"." + b))
    assert domain_matches(host, blocked) == expect


# --- Domain normalization ---------------------------------------------------

DOMAIN_CHARS = set(b"abcdefghijklmnopqrstuvwxyz0123456789-._")


def normalize(s):
    with cstr(s) as buf:
        p = lib.kb_normalize_domain(buf.ptr)
        return None if p is None else ctypes.string_at(p)


def normalize_model(s):
    s = s.strip(b" \t\n\v\f\r")
    if s.startswith(b"*."):
        s = s[2:]
    s = s.strip(b".")
    if not s or len(s) >= MAX_DOMAIN_LEN or not set(s.lower()) <= DOMAIN_CHARS:
        return None
    return s.lower()


domain_input = st.one_of(
    st.binary(max_size=300),
    st.builds(lambda pre, d, post: pre + d + post,
              st.sampled_from([b"", b" ", b"*.", b".", b"\t*..", b"*"]),
              domain,
              st.sampled_from([b"", b".", b"\n", b" ..", b"/x"])),
    st.text("a.", min_size=250, max_size=260).map(str.encode),
).map(lambda s: s.replace(b"\0", b""))


@given(domain_input)
@example(b"\xe9xample.com")
@example(b"caf\xc9.com")
@example(b"\xa0youtube.com")
def test_normalize(s):
    got = normalize(s)
    assert got == normalize_model(s)
    if got is not None:
        assert set(got) <= DOMAIN_CHARS
        assert normalize(got) == got


# --- Hex decoding -----------------------------------------------------------

def hex_decode(s, count):
    with cstr(s) as buf, CBuf(size=count) as out:
        ret = lib.kb_hex_decode(buf.ptr, out.ptr, count)
        return None if ret else out.read()


@given(st.binary(min_size=1, max_size=32), st.booleans())
def test_hex_roundtrip(raw, upper):
    h = raw.hex().encode()
    assert hex_decode(h.upper() if upper else h, len(raw)) == raw


@given(st.binary(max_size=70).map(lambda s: s.replace(b"\0", b"")),
       st.integers(1, 32))
def test_hex_decode_model(s, count):
    hexdigits = set(b"0123456789abcdefABCDEF")
    ok = len(s) >= 2 * count and set(s[:2 * count]) <= hexdigits
    assert hex_decode(s, count) == (bytes.fromhex(s[:2 * count].decode()) if ok else None)


# --- State file "remaining:" records ----------------------------------------

def last_remaining(s):
    with cstr(s) as buf:
        return lib.kb_last_remaining(buf.ptr)


def last_remaining_model(s):
    val = 0
    for m in re.finditer(rb"(?m)^remaining:([0-9]+)\n", s):
        if int(m.group(1)) <= U64_MAX:
            val = int(m.group(1))
    return val


state_text = st.lists(st.one_of(
    st.just(b"remaining:"),
    st.just(b"\n"),
    st.integers(0, 2**66).map(lambda n: str(n).encode()),
    st.sampled_from([str(U64_MAX).encode(), str(U64_MAX + 1).encode(), b"0000"]),
    st.binary(max_size=8),
), max_size=20).map(lambda parts: b"".join(parts).replace(b"\0", b""))


@given(state_text)
@example(b"remaining:18446744073709551615\n")
@example(b"remaining:18446744073709551616\n")
@example(b"remaining:5\nremaining:7")
@example(b"xremaining:5\n")
def test_last_remaining(s):
    assert last_remaining(s) == last_remaining_model(s)


@given(st.lists(st.integers(0, U64_MAX), min_size=1, max_size=10),
       st.binary(max_size=20).filter(lambda b: b"\0" not in b and b"\n" not in b))
def test_last_remaining_append_log(values, torn):
    """The append-only log yields the last complete record, even with a
    torn final write."""
    log = b"".join(b"remaining:%d\n" % v for v in values)
    assert last_remaining(log + b"remaining:" + torn) == values[-1]


# --- Hosts file block -------------------------------------------------------

def doms_array(domains, stride=MAX_DOMAIN_LEN):
    raw = b"".join(d[:stride].ljust(stride, b"\0") for d in domains)
    return CBuf(raw, size=max(len(raw), 1))


def hosts_block_model(domains, stride=MAX_DOMAIN_LEN):
    out = b"\n\n" + HOSTS_MARKER + b"\n"
    for d in domains:
        d = d[:stride]
        out += b"0.0.0.0 %s\n:: %s\n0.0.0.0 www.%s\n:: www.%s\n" % (d, d, d, d)
    return out + b"\n"


def hosts_format(domains, size=None, stride=MAX_DOMAIN_LEN):
    with doms_array(domains, stride) as doms:
        need = lib.kb_hosts_block_size(doms.ptr, len(domains), stride)
        size = need if size is None else size
        with CBuf(size=size) as out:
            n = lib.kb_hosts_format(doms.ptr, len(domains), stride, out.ptr, size)
            return need, out.read(n)


normalized_domain = st.one_of(
    domain.map(bytes.lower),
    st.text("ab.", min_size=MAX_DOMAIN_LEN - 1, max_size=MAX_DOMAIN_LEN - 1).map(str.encode),
)
domain_lists = st.lists(normalized_domain, max_size=64)


@given(domain_lists)
def test_hosts_block_exact(domains):
    need, text = hosts_format(domains)
    assert text == hosts_block_model(domains)
    assert need == len(text)


@given(domain_lists, st.data())
def test_hosts_block_bounded(domains, data):
    """A short buffer gets a prefix and is never overrun."""
    full = hosts_block_model(domains)
    size = data.draw(st.integers(0, len(full)))
    assert hosts_format(domains, size)[1] == full[:size]


@given(st.lists(st.binary(min_size=1, max_size=8).map(lambda b: b.replace(b"\0", b"a")),
                max_size=8), st.integers(1, 8))
def test_hosts_block_unterminated_stride(domains, stride):
    """Entries that fill the whole stride are cut at the stride."""
    need, text = hosts_format(domains, stride=stride)
    assert text == hosts_block_model(domains, stride)
    assert need == len(text)


def hosts_base_len(buf):
    with cstr(buf) as b:
        return lib.kb_hosts_base_len(b.ptr, len(buf))


def hosts_base_len_model(buf):
    i = buf.split(b"\0")[0].find(HOSTS_MARKER)
    return len(buf[:i if i >= 0 else len(buf)].rstrip(b"\n"))


hosts_text = st.lists(st.one_of(
    st.binary(max_size=30),
    st.just(b"\n"),
    st.just(HOSTS_MARKER),
    st.just(b"127.0.0.1 localhost\n"),
), max_size=10).map(b"".join)


@given(hosts_text)
def test_hosts_base_len(buf):
    assert hosts_base_len(buf) == hosts_base_len_model(buf)


@given(hosts_text.map(lambda s: s.replace(HOSTS_MARKER, b"").replace(b"\0", b"")),
       domain_lists, domain_lists)
def test_hosts_update_keeps_user_entries(user, first, second):
    """Writing the block twice leaves the user's entries intact and the
    file equal to user entries + the latest block."""
    def update(content, domains):
        base = hosts_base_len(content)
        return content[:base] + hosts_format(domains)[1]

    once = update(user, first)
    twice = update(once, second)
    assert twice == user.rstrip(b"\n") + hosts_block_model(second)
    assert update(twice, second) == twice
